//! 生成 `vectors/tokens/tokens.json`。
//!
//! 在 `sdk/rust` 下运行:
//!
//! ```text
//! cargo run -p map-core --features token-verify --example token_vectors \
//!   > ../../vectors/tokens/tokens.json
//! ```
//!
//! 令牌用**固定的测试密钥**签名。ed25519 是确定性签名，载荷的字段顺序也固定，
//! 所以重复运行必须得到逐字节相同的输出；不一致就说明载荷结构变了，要人工确认
//! 后再提交。这个密钥只属于向量，任何真实部署都不得使用。

use ed25519_dalek::{Signer, SigningKey};
use map_core::token::b64url_encode;
use map_core::{Capability, MemBinding, TokenClaims};
use serde_json::{json, Value};

/// 测试密钥种子（0x00..=0x1f）。固定值，改动等于换一套向量。
const SEED: [u8; 32] = [
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
    0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
];

/// 远未来时间戳（2100-01-01），保证「有效」用例永远不会自然过期。
const NEVER_EXPIRES: i64 = 4_102_444_800;

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn claims(sub: &str, caps: Vec<Capability>) -> TokenClaims {
    TokenClaims {
        sub: sub.into(),
        caps,
        iat: 1_700_000_000,
        exp: NEVER_EXPIRES,
        jti: None,
        task_id: None,
        windows: None,
        mem: None,
    }
}

fn sign(signing: &SigningKey, claims: &TokenClaims) -> String {
    let payload = serde_json::to_vec(claims).expect("claims serialize");
    let signature = signing.sign(&payload);
    format!(
        "map1.{}.{}",
        b64url_encode(&payload),
        b64url_encode(&signature.to_bytes())
    )
}

fn document(claims: &TokenClaims) -> Value {
    serde_json::to_value(claims).expect("claims to json")
}

fn main() {
    let signing = SigningKey::from_bytes(&SEED);
    let public = signing.verifying_key();

    // ---- 有效用例 ----
    let minimal = claims("client:alpha", vec![Capability::TaskRun]);

    let mut full = claims(
        "client:desktop",
        vec![
            Capability::TaskRun,
            Capability::TaskObserve,
            Capability::DisplayView,
            Capability::DisplayInput,
        ],
    );
    full.jti = Some("01J8Z0Q2X4N7V3M9K1P5R6T8W0".into());
    full.task_id = Some("01J8Z0Q2X4N7V3M9K1P5R6T8W1".into());
    full.windows = Some(vec![3, 7]);
    full.mem = Some(MemBinding {
        providers: Some(vec!["local".into(), "remote:lab".into()]),
        write: true,
    });

    let admin = claims("client:operator", vec![Capability::Admin]);

    // ---- 无效用例（令牌层面，schema 拦不住）----
    let mut expired = claims("client:alpha", vec![Capability::TaskRun]);
    expired.iat = 1_600_000_000;
    expired.exp = 1_600_003_600;

    // 用另一个载荷的签名冒充：payload 与 sig 不配对。
    let other = claims("client:beta", vec![Capability::Admin]);
    let foreign_signature = sign(&signing, &other);
    let foreign_sig_segment = foreign_signature
        .rsplit_once('.')
        .expect("token has two segments")
        .1;
    let minimal_token = sign(&signing, &minimal);
    let minimal_payload = minimal_token
        .strip_prefix("map1.")
        .and_then(|rest| rest.split_once('.'))
        .expect("token has two segments")
        .0;
    let mismatched = format!("map1.{minimal_payload}.{foreign_sig_segment}");

    let not_json_payload = b64url_encode(b"not json");
    let not_json = format!("map1.{not_json_payload}.{foreign_sig_segment}");

    let doc = json!({
        "$comment": concat!(
            "map1. capability tokens (RFC 0001 §transport-security). ",
            "Generated by sdk/rust/crates/map-core/examples/token_vectors.rs with a fixed ",
            "test key; the public key below is the pin — a token only passes if it ",
            "verifies against it. Do not hand-edit: regenerate instead."
        ),
        "schema": "../schemas/token.schema.json",
        "issuer": {
            "algorithm": "ed25519",
            "public_key_hex": hex(&public.to_bytes()),
            "seed_hex": hex(&SEED),
            "warning": "Test-only key. Never use it to issue a real token.",
        },
        "valid": [
            {
                "name": "minimal claims",
                "document": document(&minimal),
                "token": minimal_token.clone(),
            },
            {
                "name": "full claims (jti, taskId, windows, mem)",
                "document": document(&full),
                "token": sign(&signing, &full),
            },
            {
                "name": "admin-only",
                "document": document(&admin),
                "token": sign(&signing, &admin),
            },
        ],
        "invalid": [
            {
                "name": "expired token",
                "code": "unauthorized",
                "semantic": true,
                "rejects": "parse",
                "document": document(&expired),
                "token": sign(&signing, &expired),
            },
            {
                "name": "signature from another payload",
                "code": "unauthorized",
                "semantic": true,
                "rejects": "verify",
                "document": document(&minimal),
                "token": mismatched,
            },
            {
                "name": "payload is not JSON",
                "code": "unauthorized",
                "semantic": true,
                "rejects": "parse",
                "document": document(&minimal),
                "token": not_json,
            },
            {
                "name": "wrong version prefix",
                "code": "unauthorized",
                "semantic": true,
                "rejects": "parse",
                "document": document(&minimal),
                "token": minimal_token.replacen("map1.", "map2.", 1),
            },
            {
                "name": "missing signature segment",
                "code": "unauthorized",
                "semantic": true,
                "rejects": "parse",
                "document": document(&minimal),
                "token": format!("map1.{minimal_payload}"),
            },
            {
                "name": "invalid base64url character",
                "code": "unauthorized",
                "semantic": true,
                "rejects": "parse",
                "document": document(&minimal),
                "token": format!("map1.!!!!.{foreign_sig_segment}"),
            },
            {
                "name": "empty caps",
                "code": "bad_request",
                "document": json!({
                    "sub": "client:alpha",
                    "caps": [],
                    "iat": 1_700_000_000,
                    "exp": NEVER_EXPIRES,
                }),
            },
            {
                "name": "unknown capability",
                "code": "bad_request",
                "document": json!({
                    "sub": "client:alpha",
                    "caps": ["task.destroy"],
                    "iat": 1_700_000_000,
                    "exp": NEVER_EXPIRES,
                }),
            },
            {
                "name": "missing sub",
                "code": "bad_request",
                "document": json!({
                    "caps": ["task.run"],
                    "iat": 1_700_000_000,
                    "exp": NEVER_EXPIRES,
                }),
            },
        ],
    });

    println!(
        "{}",
        serde_json::to_string_pretty(&doc).expect("vector doc serializes")
    );
}
